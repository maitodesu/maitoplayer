import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const repositoryRoot = resolve(import.meta.dirname, '..', '..');
const rustPath = resolve(repositoryRoot, 'crates', 'contracts', 'src', 'lib.rs');
const outputPath = resolve(
  repositoryRoot,
  'apps',
  'desktop',
  'ui',
  'src',
  'lib',
  'contracts',
  'generated.ts',
);
const source = await readFile(rustPath, 'utf8');

function snakeCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
}

function innerGeneric(type, wrapper) {
  const prefix = `${wrapper}<`;
  return type.startsWith(prefix) && type.endsWith('>')
    ? type.slice(prefix.length, -1).trim()
    : null;
}

function typescriptType(rustType) {
  const type = rustType.replaceAll('std::collections::', '').trim();
  const optional = innerGeneric(type, 'Option');
  if (optional !== null) return `${typescriptType(optional)} | null`;
  const vector = innerGeneric(type, 'Vec');
  if (vector !== null) return `${typescriptType(vector)}[]`;
  const map = type.match(/^BTreeMap<String,\s*String>$/);
  if (map) return 'Record<string, string>';
  if (type === 'String' || type === '&str') return 'string';
  if (type === 'bool') return 'boolean';
  if (/^[ui](8|16|32|64|128|size)$/.test(type) || /^f(32|64)$/.test(type)) return 'number';
  if (/^[A-Za-z][A-Za-z0-9_]*$/.test(type)) return type;
  throw new Error(`Unsupported public Rust contract type: ${rustType}`);
}

function blockEnd(openBrace) {
  let depth = 0;
  for (let index = openBrace; index < source.length; index += 1) {
    if (source[index] === '{') depth += 1;
    if (source[index] === '}') depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`Unclosed public contract block at byte ${openBrace}`);
}

const declarations = [];
for (const match of source.matchAll(/^opaque_id!\((\w+)\);$/gm)) {
  declarations.push({ offset: match.index, text: `export type ${match[1]} = string;` });
}
for (const match of source.matchAll(/^pub type (\w+) = ([^;]+);$/gm)) {
  declarations.push({
    offset: match.index,
    text: `export type ${match[1]} = ${typescriptType(match[2])};`,
  });
}
for (const match of source.matchAll(/^pub (struct|enum) (\w+)\s*\{/gm)) {
  const [, kind, name] = match;
  const openBrace = source.indexOf('{', match.index);
  const body = source.slice(openBrace + 1, blockEnd(openBrace));
  if (kind === 'enum') {
    const variants = [...body.matchAll(/^\s*([A-Z][A-Za-z0-9_]*)\s*,?\s*$/gm)].map(
      (variant) => `'${snakeCase(variant[1])}'`,
    );
    if (variants.length === 0) throw new Error(`Public enum ${name} has no unit variants`);
    declarations.push({ offset: match.index, text: `export type ${name} = ${variants.join(' | ')};` });
    continue;
  }
  const fields = [...body.matchAll(/^\s*pub\s+(\w+):\s*(.+),\s*$/gm)].map((field) => {
    const rustType = field[2].trim();
    return `  ${field[1]}: ${typescriptType(rustType)};`;
  });
  if (fields.length === 0) throw new Error(`Public struct ${name} has no public fields`);
  declarations.push({
    offset: match.index,
    text: `export interface ${name} {\n${fields.join('\n')}\n}`,
  });
}

declarations.sort((left, right) => left.offset - right.offset);
const generated = [
  '// Generated from crates/contracts/src/lib.rs by tools/contracts/generate-typescript.mjs.',
  '// Regenerate with `pnpm generate:contracts`; do not edit this file manually.',
  '// Public contracts contain opaque identifiers and scoped URLs, never filesystem paths.',
  '',
  declarations.map((declaration) => declaration.text).join('\n\n'),
  '',
].join('\n');

await writeFile(outputPath, generated, 'utf8');
